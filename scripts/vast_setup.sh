#!/usr/bin/env bash
# One-time setup on a Vast.ai instance started from the lab image joowan1108/dsrl-robocasa365:v1
# (built in the SkillPatch project). That image already has, under /opt:
#   /opt/venvs/sim       py3.11, robocasa @425684d (same files we use as 7bfc60c), robosuite, torch 2.7.1, lerobot
#   /opt/venvs/xr1       py3.12, torch 2.8, transformers 4.57.1, flash-attn 2.8.3
#   /opt/src/RLDX-1/.venv  RLDX-1 v1.0.2 (torch 2.7.0)
# and its On-start script downloads RoboCasa assets + both checkpoints to /workspace/checkpoints
# (progress: /workspace/download.log). The torch builds target RTX 40-series: rent RTX 4090, not 5090.
#
#   bash scripts/vast_setup.sh        # then:  source vast.env
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
unset VIRTUAL_ENV
SIM=/opt/venvs/sim/bin/python
XR1=/opt/venvs/xr1/bin/python
RLDX_REPO=/opt/src/RLDX-1
RLDX=$RLDX_REPO/.venv/bin/python
CK=/workspace/checkpoints

for p in "$SIM" "$XR1" "$RLDX"; do [[ -x $p ]] || { echo "[x] missing $p (is this the dsrl-robocasa365 image?)"; exit 1; }; done

# PLD process: this package without touching the pinned torch/numpy/opencv of the sim env
uv pip install --python "$SIM" --no-deps -e "$REPO"
uv pip install --python "$SIM" pyzmq timm pyyaml pandas
# XR1 server + our LoRA trainer
uv pip install --python "$XR1" pyzmq peft av pandas pyarrow pyyaml
# RLDX server (RLDX ships its own ZeroMQ server, so pyzmq is normally already there)
"$RLDX" -c "import zmq" 2>/dev/null || uv pip install --python "$RLDX" pyzmq

cat > "$REPO/vast.env" <<EOF
# generated by scripts/vast_setup.sh -- source this before running anything
unset VIRTUAL_ENV
export PLD_SIM_PY=$SIM
export PLD_XR1_PY=$XR1
export PLD_RLDX_PY=$RLDX
export RLDX_REPO=$RLDX_REPO
export XR1_MODEL=$CK/Xiaomi-Robotics-1-RoboCasa365
export RLDX_MODEL=$CK/RLDX-1-FT-RC365
export HF_HOME=\${HF_HOME:-/workspace/hf_cache}
export MUJOCO_GL=egl PYOPENGL_PLATFORM=egl PYTHONUNBUFFERED=1 TOKENIZERS_PARALLELISM=false
EOF

# import checks (no GPU work)
( cd "$REPO" && "$SIM" -c "import pld_rc365.stage1_train, pld_rc365.stage2_collect, pld_rc365.eval, timm, zmq; print('[ok] sim env')" )
( cd "$REPO" && "$XR1" -c "import peft, av, zmq, pld_rc365.sft.xr1_lora_train; print('[ok] xr1 env')" )
( cd "$REPO" && "$RLDX" -c "import zmq, rldx; print('[ok] rldx env')" )

echo "[i] memory limit (cgroup): $(cat /sys/fs/cgroup/memory.max 2>/dev/null || cat /sys/fs/cgroup/memory/memory.limit_in_bytes 2>/dev/null || echo n/a) bytes -- ~6.5 GB per env + replay buffer"
nvidia-smi --query-gpu=name,memory.total --format=csv,noheader || true
for d in Xiaomi-Robotics-1-RoboCasa365 RLDX-1-FT-RC365; do
  [[ -f $CK/$d/config.json ]] && echo "[ok] checkpoint $d" || echo "[..] checkpoint $d not there yet (tail -f /workspace/download.log)"
done
echo "[ok] setup done. Next:  source vast.env && bash scripts/run_experiment1.sh"
